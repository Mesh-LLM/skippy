use anyhow::{Result, ensure};
use serde::Serialize;
use skippy_model_artifact::support::{
    ArchitectureProfile, ArchitectureTrack, PhaseOneFixture, PhaseOneManifest,
    bundled_architecture_profiles, valid_sha256,
};
use std::io::Write;

#[derive(Clone, Copy, Serialize)]
#[serde(rename_all = "snake_case")]
enum Evidence {
    Correctness,
    Cache,
    Performance,
    Graph,
    StateHandoff,
}

const TIER_A_EVIDENCE: &[Evidence] = &[
    Evidence::Correctness,
    Evidence::Cache,
    Evidence::Performance,
];
const TIER_B_EVIDENCE: &[Evidence] = &[
    Evidence::Graph,
    Evidence::StateHandoff,
    Evidence::Correctness,
];

#[derive(Serialize)]
#[serde(rename_all = "snake_case")]
enum Status {
    PendingEvidence,
    Experimental,
    Unsupported,
}

#[derive(Serialize)]
struct ModelRow<'a> {
    status: Status,
    qualification_target: &'static str,
    required_evidence: &'static [Evidence],
    #[serde(flatten)]
    fixture: &'a PhaseOneFixture,
}

#[derive(Serialize)]
struct ArchitectureRow<'a> {
    status: Status,
    required_evidence: &'static [Evidence],
    #[serde(flatten)]
    profile: &'a ArchitectureProfile,
}

pub(super) fn run(sha256: Option<&str>, json: bool) -> Result<()> {
    let models = PhaseOneManifest::bundled()?;
    if let Some(sha256) = sha256 {
        ensure!(
            valid_sha256(sha256),
            "expected a lowercase artifact SHA-256"
        );
        let model = models.models.iter().find(|model| model.sha256 == sha256);
        if json {
            let response = match model {
                Some(model) => serde_json::json!({"schema_version":1, "model":model_row(model)}),
                None => {
                    serde_json::json!({"schema_version":1, "status":Status::Unsupported, "sha256":sha256})
                }
            };
            return write_json(&response);
        }
        let mut output = super::output::console_out();
        if let Some(model) = model {
            writeln!(
                output,
                "{}@{}:{}  Tier A candidate, pending evidence",
                model.repo,
                model.revision,
                model.quantization.as_str()
            )?;
        } else {
            writeln!(output, "Unsupported artifact identity {sha256}")?;
        }
        return Ok(());
    }

    let architectures = bundled_architecture_profiles()?;
    if json {
        let phase_one: Vec<_> = models.models.iter().map(model_row).collect();
        let architectures: Vec<_> = architectures
            .iter()
            .map(|profile| ArchitectureRow {
                status: match profile.track {
                    ArchitectureTrack::TierB => Status::PendingEvidence,
                    ArchitectureTrack::Experimental => Status::Experimental,
                },
                required_evidence: if profile.track == ArchitectureTrack::TierB {
                    TIER_B_EVIDENCE
                } else {
                    &[]
                },
                profile,
            })
            .collect();
        return write_json(
            &serde_json::json!({"schema_version":1,"phase_one":phase_one,"architectures":architectures}),
        );
    }
    write_markdown(
        &mut super::output::console_out(),
        &models.models,
        &architectures,
    )?;
    Ok(())
}

fn model_row(fixture: &PhaseOneFixture) -> ModelRow<'_> {
    ModelRow {
        status: Status::PendingEvidence,
        qualification_target: "tier_a",
        required_evidence: TIER_A_EVIDENCE,
        fixture,
    }
}

fn write_json(value: &serde_json::Value) -> Result<()> {
    let mut output = super::output::machine_out();
    serde_json::to_writer_pretty(&mut output, value)?;
    writeln!(output)?;
    Ok(())
}

fn write_markdown(
    output: &mut impl Write,
    models: &[PhaseOneFixture],
    architectures: &[ArchitectureProfile],
) -> std::io::Result<()> {
    writeln!(
        output,
        "# Skippy model support\n\n<!-- Generated by `skippy models support`. -->\n\n## Phase 1 Tier A candidates\n"
    )?;
    writeln!(
        output,
        "Tier A requires matching correctness, cache, and performance results for the exact artifact.\n"
    )?;
    writeln!(
        output,
        "| Family | Artifact | Quantization | Status |\n| --- | --- | --- | --- |"
    )?;
    for model in models {
        writeln!(
            output,
            "| {} | `{}@{}` | `{}` | Pending evidence |",
            model.family.as_str(),
            model.repo,
            model.revision,
            model.quantization.as_str()
        )?;
    }
    writeln!(
        output,
        "\n## Architecture qualification\n\nTier B requires graph, state-handoff, and correctness evidence.\n\n| Architecture | Canary fixture | Status |\n| --- | --- | --- |"
    )?;
    for profile in architectures {
        let status = match profile.track {
            ArchitectureTrack::TierB => "Tier B candidate",
            ArchitectureTrack::Experimental => "Experimental",
        };
        writeln!(
            output,
            "| `{}` | `{}` | {} |",
            profile.architecture, profile.canary_fixture, status
        )?;
    }
    for note in architectures
        .iter()
        .filter_map(|profile| profile.note.as_deref())
    {
        writeln!(output, "\n{note}")?;
    }
    writeln!(
        output,
        "\nUse `skippy models support --json` for immutable filenames, file sizes, digests, sidecars, and licenses. Use `--sha256` to look up an exact Phase 1 model identity. Model loading follows the serving settings."
    )
}
